-- 1) Profiles (extends auth.users)
create table if not exists public.profiles (
  id uuid references auth.users not null primary key,
  email text unique not null,
  name text,
  role text default 'user' check (role in ('user', 'superadmin')),
  created_at timestamptz default now(),
  telegram_chat_id bigint,
  telegram_username text
);

alter table public.profiles enable row level security;

create policy "Profiles are viewable by everyone"
  on public.profiles for select using ( true );

create policy "Users can update own profile"
  on public.profiles for update using ( auth.uid() = id );

-- Superadmin checks use a SECURITY DEFINER helper: a policy on profiles that
-- queries profiles itself causes infinite recursion in PostgREST (42P17).
create or replace function public.is_superadmin()
returns boolean
language sql
security definer
stable
set search_path = public
as $$
  select exists (
    select 1 from public.profiles where id = auth.uid() and role = 'superadmin'
  );
$$;

drop policy if exists "Superadmin can manage all profiles" on public.profiles;
create policy "Superadmin can manage all profiles"
  on public.profiles for all using ( public.is_superadmin() );

-- Trigger to automatically create a profile when a user signs up
create or replace function public.handle_new_user()
returns trigger as $$
begin
  insert into public.profiles (id, email, name)
  values (new.id, coalesce(new.email, ''), coalesce(new.raw_user_meta_data->>'name', 'Movie Fan'))
  on conflict (id) do update set
    email = excluded.email,
    name = coalesce(excluded.name, public.profiles.name);
  return new;
end;
$$ language plpgsql security definer;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

-- 2) Cities
create table if not exists public.cities (
  id bigint generated by default as identity primary key,
  name text not null,
  code text not null,
  source text not null check (source in ('bookmyshow', 'district')),
  created_at timestamptz default now(),
  unique (name, code, source)
);

-- 3) Movies
create table if not exists public.movies (
  id bigint generated by default as identity primary key,
  source_movie_id text not null,
  title text not null,
  poster_url text,
  language text,
  genre text,
  duration text,
  release_date text,
  city_code text not null,
  source text not null check (source in ('bookmyshow', 'district')),
  is_bookable boolean default false,
  bookable_url text,
  fetched_at timestamptz default now(),
  unique (source_movie_id, city_code, source)
);

-- 4) Theaters
create table if not exists public.theaters (
  id bigint generated by default as identity primary key,
  source_theater_id text not null,
  name text not null,
  address text,
  city_code text not null,
  source text not null check (source in ('bookmyshow', 'district')),
  created_at timestamptz default now(),
  unique (source_theater_id, city_code, source)
);

-- 5) Movie-Theater links
create table if not exists public.movie_theaters (
  movie_id bigint references public.movies(id) on delete cascade,
  theater_id bigint references public.theaters(id) on delete cascade,
  source text not null,
  primary key (movie_id, theater_id, source)
);

-- 6) Telegram links (user <-> telegram chat)
create table if not exists public.telegram_links (
  id bigint generated by default as identity primary key,
  user_id uuid references public.profiles(id) on delete cascade unique,
  telegram_chat_id bigint unique,
  telegram_username text,
  bot_token text,
  connected_at timestamptz default now(),
  updated_at timestamptz default now()
);

-- 7) Telegram OTPs (for connecting via @movietracker bot)
create table if not exists public.telegram_otps (
  id bigint generated by default as identity primary key,
  user_id uuid references public.profiles(id) on delete cascade not null,
  otp_code text not null,
  expires_at timestamptz not null,
  is_used boolean default false,
  created_at timestamptz default now()
);

-- 8) Alerts
create table if not exists public.alerts (
  id bigint generated by default as identity primary key,
  user_id uuid references public.profiles(id) on delete cascade not null,
  telegram_chat_id bigint,
  movie_title text not null,
  source_movie_id text,
  slug text,
  city_code text not null,
  city_name text,
  source text not null check (source in ('bookmyshow', 'district')),
  theater_name text,
  theater_id text,
  is_active boolean default true,
  status text default 'pending', -- 'pending', 'triggered', 'error'
  created_at timestamptz default now(),
  last_notified_at timestamptz,
  last_checked_at timestamptz
);

-- Ensure columns exist if table was already created
alter table public.alerts add column if not exists source_movie_id text;
alter table public.alerts add column if not exists slug text;
alter table public.alerts add column if not exists city_name text;
alter table public.alerts add column if not exists theater_id text;
alter table public.alerts add column if not exists status text default 'pending';
alter table public.alerts add column if not exists last_checked_at timestamptz;
-- structured alert flow: language picker, chosen show date, cross-platform id
alter table public.alerts add column if not exists language text;
alter table public.alerts add column if not exists target_date text;
alter table public.alerts add column if not exists alt_source_movie_id text;

-- indexes for polling performance
create index if not exists idx_alerts_active on public.alerts(is_active);
create index if not exists idx_alerts_user on public.alerts(user_id);
create index if not exists idx_telegram_otps_code on public.telegram_otps(otp_code);
create index if not exists idx_telegram_otps_user on public.telegram_otps(user_id);
create index if not exists idx_telegram_links_chat on public.telegram_links(telegram_chat_id);
create index if not exists idx_movies_source_city on public.movies(source, city_code);
create index if not exists idx_cities_source on public.cities(source);

